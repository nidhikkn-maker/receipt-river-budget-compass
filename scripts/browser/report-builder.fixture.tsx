import React from 'react';
import { createRoot } from 'react-dom/client';
import '/src/styles.css';
import { ExpenditureReportBuilder } from '/src/components/ExpenditureReportBuilder.tsx';
import { createRootRoute, createRouter, RouterProvider } from '@tanstack/react-router';
const claim = new URLSearchParams(window.location.search).get('mode') === 'claim';
const mount = document.getElementById('root');
const route=createRootRoute({component:()=> <main className="mx-auto max-w-4xl p-4"><ExpenditureReportBuilder mode={claim ? 'claim' : 'statement'} search={claim ? { entries: 'e,missing,broken' } : { entry: 'e' }} /></main>});
const router=createRouter({routeTree:route});
if (mount) createRoot(mount).render(<RouterProvider router={router}/>);