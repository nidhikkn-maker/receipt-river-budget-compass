import {createRoot} from 'react-dom/client';
import {createRootRoute,createRoute,createRouter,Outlet,RouterProvider} from '@tanstack/react-router';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import {Route as Inbox} from '../../src/routes/_authenticated/inbox';
import {Route as Audit} from '../../src/routes/_authenticated/audit';
import {Route as Reports} from '../../src/routes/_authenticated/report-centre';
import {Route as Gst} from '../../src/routes/_authenticated/gst-check';
import {Toaster} from '../../src/components/ui/sonner';
import '../../src/styles.css';
const query=new QueryClient();
const root=createRootRoute({component:()=> <QueryClientProvider client={query}><Outlet/><Toaster/></QueryClientProvider>});
const auth=createRoute({getParentRoute:()=>root,id:'_authenticated',component:Outlet});
const children=[Inbox.update({id:'/inbox',path:'/inbox',getParentRoute:()=>auth}),Audit.update({id:'/audit',path:'/audit',getParentRoute:()=>auth}),Reports.update({id:'/report-centre',path:'/report-centre',getParentRoute:()=>auth}),Gst.update({id:'/gst-check',path:'/gst-check',getParentRoute:()=>auth})];
const router=createRouter({routeTree:root.addChildren([auth.addChildren(children)])});
const mount=document.getElementById('root');if(mount)createRoot(mount).render(<RouterProvider router={router}/>);